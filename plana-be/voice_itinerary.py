"""Server-side itinerary operations used by the LiveKit voice worker.

The worker never receives Supabase credentials. It calls the FastAPI endpoints in
``main.py``; this module keeps the database access and itinerary validation within
the existing backend and its LangGraph planning code.
"""

from __future__ import annotations

from copy import deepcopy
import re
from typing import Any

from pydantic import BaseModel, Field, field_validator

from agent.graph import parse_time_to_minutes, validate_node
from database import (
    get_conversation_by_phone_number,
    get_existing_active_trip,
    save_trip,
)


class VoiceTripNotFoundError(Exception):
    """Raised when a voice room is not bound to an existing trip session."""


class VoiceItineraryConflictError(Exception):
    """Raised when an edit is stale, ambiguous, or makes the itinerary invalid."""


class VoiceItineraryEdit(BaseModel):
    """A bounded itinerary mutation generated by the realtime voice agent."""

    request_id: str = Field(min_length=1, max_length=200)
    expected_revision: int = Field(ge=0)
    day_number: int = Field(ge=1)
    event_name: str = Field(min_length=1, max_length=240)
    new_start_time: str = Field(min_length=1, max_length=32)
    new_end_time: str = Field(min_length=1, max_length=32)

    @field_validator("new_start_time", "new_end_time")
    @classmethod
    def validate_time(cls, value: str) -> str:
        minutes = parse_time_to_minutes(value)
        if minutes is None or not 0 <= minutes < 24 * 60:
            raise ValueError("Use a time such as '2:30 PM' or '14:30'.")
        return value


def _normalized_name(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip().casefold()


def _itinerary_revision(state: dict[str, Any]) -> int:
    revision = state.get("itinerary_revision", 0)
    return revision if isinstance(revision, int) and revision >= 0 else 0


def _voice_itinerary_context(itinerary: Any) -> dict[str, Any] | None:
    """Project only the schedule details Gemini needs for a voice edit."""
    if not isinstance(itinerary, dict) or not isinstance(itinerary.get("days"), list):
        return None

    days: list[dict[str, Any]] = []
    for day in itinerary["days"]:
        if not isinstance(day, dict):
            continue
        events = day.get("events")
        if not isinstance(events, list):
            continue
        days.append(
            {
                "day_number": day.get("day_number"),
                "date": day.get("date"),
                "events": [
                    {
                        "type": event.get("type"),
                        "name": event.get("name"),
                        "start_time": event.get("start_time"),
                        "end_time": event.get("end_time"),
                    }
                    for event in events
                    if isinstance(event, dict)
                ],
            }
        )
    return {"days": days}


def _voice_hotel_context(hotel: Any) -> dict[str, Any] | None:
    if not isinstance(hotel, dict):
        return None
    return {"name": hotel.get("name"), "address": hotel.get("address")}


def _format_time(minutes: int) -> str:
    hour = minutes // 60
    minute = minutes % 60
    period = "AM" if hour < 12 else "PM"
    display_hour = hour % 12 or 12
    return f"{display_hour}:{minute:02d} {period}"


async def _load_voice_trip(session_id: str) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]:
    conversation = await get_conversation_by_phone_number(session_id)
    if not conversation:
        raise VoiceTripNotFoundError("Start a trip in the planner before using voice edits.")

    trip = await get_existing_active_trip(
        conversation["id"],
        conversation.get("active_trip_id"),
    )
    if not trip:
        raise VoiceTripNotFoundError("This trip does not have an itinerary yet.")
    state = trip.get("state_json")
    if not isinstance(state, dict):
        raise VoiceTripNotFoundError("This trip does not have a readable itinerary yet.")

    return conversation, trip, state


async def get_voice_trip_context(session_id: str) -> dict[str, Any]:
    """Return a concise, server-authoritative itinerary context for Gemini Live."""
    _, trip, state = await _load_voice_trip(session_id)

    return {
        "sessionId": session_id,
        "tripId": trip["id"],
        "revision": _itinerary_revision(state),
        "trip": {
            "destination": state.get("destination"),
            "start_date": state.get("start_date"),
            "end_date": state.get("end_date"),
            "travelers": state.get("travelers"),
            "interests": state.get("interests", []),
            "dislikes": state.get("dislikes", []),
            "budget": state.get("budget", {}),
            "selected_hotel": _voice_hotel_context(state.get("selected_hotel")),
            "itinerary": _voice_itinerary_context(state.get("itinerary")),
        },
    }


def _validate_day_event_sequence(events: list[Any]) -> None:
    """Keep an edit inside the generated timeline's chronological order."""
    previous_event: dict[str, Any] | None = None
    previous_end: int | None = None
    for event in events:
        if not isinstance(event, dict):
            raise VoiceItineraryConflictError("This itinerary has an invalid event.")

        start = parse_time_to_minutes(str(event.get("start_time", "")))
        end = parse_time_to_minutes(str(event.get("end_time", "")))
        if start is None or end is None or end < start:
            raise VoiceItineraryConflictError(
                f"{event.get('name', 'That event')} has an invalid scheduled time."
            )
        if previous_end is not None and start < previous_end:
            previous_name = previous_event.get("name", "the previous event") if previous_event else "the previous event"
            raise VoiceItineraryConflictError(
                f"That time overlaps with {previous_name}. Choose a time within the open slot."
            )
        previous_event = event
        previous_end = end


async def reschedule_voice_itinerary_event(
    session_id: str,
    edit: VoiceItineraryEdit,
) -> dict[str, Any]:
    """Apply one validated time change and persist it through the existing backend.

    The current LangGraph validator remains the source of truth for opening-hour,
    travel-buffer, and budget validation. An invalid change is rejected without
    changing Supabase or the SQLite fallback.
    """
    _, trip, saved_state = await _load_voice_trip(session_id)
    itinerary = saved_state.get("itinerary")
    if not isinstance(itinerary, dict) or not isinstance(itinerary.get("days"), list):
        raise VoiceItineraryConflictError(
            "There is no generated itinerary to edit yet. Ask me to plan the trip first."
        )

    edit_history = saved_state.get("voice_edit_history", [])
    if not isinstance(edit_history, list):
        edit_history = []
    for previous_edit in edit_history:
        if isinstance(previous_edit, dict) and previous_edit.get("request_id") == edit.request_id:
            return {
                "sessionId": session_id,
                "tripId": trip["id"],
                "revision": _itinerary_revision(saved_state),
                "summary": previous_edit.get("summary", "That itinerary update is already saved."),
            }

    current_revision = _itinerary_revision(saved_state)
    if edit.expected_revision != current_revision:
        raise VoiceItineraryConflictError(
            "The itinerary changed while I was working. Please ask me to try that edit again."
        )

    updated_state = deepcopy(saved_state)
    days = updated_state["itinerary"]["days"]
    day = next(
        (
            item
            for item in days
            if isinstance(item, dict) and item.get("day_number") == edit.day_number
        ),
        None,
    )
    if not day or not isinstance(day.get("events"), list):
        raise VoiceItineraryConflictError(f"I could not find day {edit.day_number} in this itinerary.")

    matching_events = [
        (index, event)
        for index, event in enumerate(day["events"])
        if isinstance(event, dict)
        and event.get("type") in {"activity", "meal"}
        and _normalized_name(str(event.get("name", ""))) == _normalized_name(edit.event_name)
    ]
    if not matching_events:
        raise VoiceItineraryConflictError(
            f"I could not find {edit.event_name} on day {edit.day_number}."
        )
    if len(matching_events) > 1:
        raise VoiceItineraryConflictError(
            f"There is more than one {edit.event_name} on day {edit.day_number}. Please be more specific."
        )

    new_start_minutes = parse_time_to_minutes(edit.new_start_time)
    new_end_minutes = parse_time_to_minutes(edit.new_end_time)
    assert new_start_minutes is not None and new_end_minutes is not None
    if new_end_minutes <= new_start_minutes:
        raise VoiceItineraryConflictError("The end time must be after the start time.")

    _, event = matching_events[0]
    previous_start_time = str(event.get("start_time", ""))
    previous_end_time = str(event.get("end_time", ""))
    event["start_time"] = _format_time(new_start_minutes)
    event["end_time"] = _format_time(new_end_minutes)
    event["duration_minutes"] = new_end_minutes - new_start_minutes
    _validate_day_event_sequence(day["events"])

    # Existing LangGraph data is trusted as the validation input. These defaults
    # only protect legacy partial states from a KeyError in validate_node.
    updated_state.setdefault("places", [])
    updated_state.setdefault("selected_hotel", None)
    updated_state.setdefault("budget", {})
    validation = await validate_node(updated_state)
    if validation.get("validation_status") != "valid":
        messages = [
            str(issue.get("message", "The change conflicts with the itinerary."))
            for issue in validation.get("issues", [])
            if isinstance(issue, dict)
        ]
        raise VoiceItineraryConflictError(" ".join(messages) or "That time does not fit the itinerary.")

    updated_state.update(validation)
    next_revision = current_revision + 1
    summary = (
        f"Moved {event['name']} on day {edit.day_number} from "
        f"{previous_start_time}–{previous_end_time} to "
        f"{event['start_time']}–{event['end_time']}."
    )
    updated_state["itinerary_revision"] = next_revision
    updated_state["voice_edit_history"] = [
        *edit_history[-19:],
        {
            "request_id": edit.request_id,
            "revision": next_revision,
            "summary": summary,
        },
    ]

    await save_trip(trip["id"], updated_state, status=trip.get("status") or "planned")

    return {
        "sessionId": session_id,
        "tripId": trip["id"],
        "revision": next_revision,
        "summary": summary,
    }
